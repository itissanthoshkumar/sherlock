def _variant_balance(child_txn_id: str) -> float:
    """Deterministic per-loan balance in [800, 24800) so a mock cycle spreads
    customers across all buckets instead of everyone landing on 2.95. Same
    child txn id -> same balance on every run and retry. The header balance
    intentionally differs from the transaction tail (real-report txns are
    kept untouched) — acceptable for the demo."""
    import zlib
    return float(800 + (zlib.crc32(str(child_txn_id).encode()) % 24000))


